/** Every generated file, as a path relative to `android/app/src/main`. */
function generatedFiles(packageName) {
  return {
    [`java/${packageName.split('.').join('/')}/${PROVIDER_CLASS}.kt`]:
      providerKotlin(packageName),
    'res/layout/pawtrack_seizure_widget.xml': layoutXml,
    'res/xml/pawtrack_seizure_widget_info.xml': widgetInfoXml,
    'res/drawable/pawtrack_widget_background.xml': backgroundXml,
    'res/drawable/pawtrack_widget_record_ring.xml': recordRingXml,
    'res/drawable-v31/pawtrack_widget_background.xml': backgroundXmlV31,
    'res/values/pawtrack_widget_strings.xml': stringsXml,
  };
}

const withWidgetSources = (config) =>
  withDangerousMod(config, [
    'android',
    async (config) => {
      const packageName = config.android?.package;
      if (!packageName) {
        // Loud on purpose. Silently skipping would produce a build that works
        // and simply has no widget, with nothing anywhere saying why.
        throw new Error(
          '[withSeizureWidget] android.package is not set in app.config.ts; ' +
            'the widget provider has no package to live in.',
        );
      }

      const main = path.join(
        config.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
      );

      for (const [relative, contents] of Object.entries(generatedFiles(packageName))) {
        const file = path.join(main, relative);
        await fs.promises.mkdir(path.dirname(file), { recursive: true });
        await fs.promises.writeFile(file, contents, 'utf8');
      }

      return config;
    },
  ]);

/**
 * Adds the `<receiver>`.
 *
 * `exported="false"` is correct and is what Android's own widget documentation
 * uses: the APPWIDGET_UPDATE broadcast comes from the system as an explicit
 * intent to this component, so it does not need to be reachable by other apps
 * — and making it reachable would let any app on the device trigger it.
 */
function addReceiver(androidManifest, packageName) {
  const application =
    AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  const name = `${packageName}.${PROVIDER_CLASS}`;

  application.receiver = application.receiver ?? [];
  // Idempotent: prebuild without --clean re-runs mods over a manifest that may
  // already carry the receiver, and two would be a manifest merger failure.
  application.receiver = application.receiver.filter(
    (receiver) => receiver.$?.['android:name'] !== name,
  );

  application.receiver.push({
    $: {
      'android:name': name,
      'android:exported': 'false',
      'android:label': '@string/pawtrack_seizure_widget_label',
    },
    'intent-filter': [
      {
        action: [
          { $: { 'android:name': 'android.appwidget.action.APPWIDGET_UPDATE' } },
        ],
      },
    ],
    'meta-data': [
      {
        $: {
          'android:name': 'android.appwidget.provider',
          'android:resource': '@xml/pawtrack_seizure_widget_info',
        },
      },
    ],
  });

  return androidManifest;
}

const withWidgetReceiver = (config) =>
  withAndroidManifest(config, (config) => {
    config.modResults = addReceiver(
      config.modResults,
      config.android?.package ?? '',
    );
    return config;
  });

const withSeizureWidget = (config) =>
  withWidgetReceiver(withWidgetSources(config));

module.exports = withSeizureWidget;
