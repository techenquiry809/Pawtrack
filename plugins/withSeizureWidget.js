/**
 * The same tile, rounded to the launcher's own radius on Android 12+.
 *
 * From API 31 the system gives widgets a device-specific corner radius, and a
 * tile that hardcodes its own sits visibly inside the cut corner. There is a
 * platform dimension for it, but only from 31 — hence two copies of the
 * drawable rather than one: `drawable-v31` reads the system value, plain
 * `drawable` keeps the fixed 26dp for everything older.
 */
const backgroundXmlV31 = backgroundXml.replace(
  'android:radius="26dp"',
  'android:radius="@android:dimen/system_app_widget_background_radius"',
);

